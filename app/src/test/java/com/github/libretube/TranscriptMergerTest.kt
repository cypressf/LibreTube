package com.github.libretube

import com.github.libretube.obj.TranscriptLine
import com.github.libretube.util.TranscriptMerger
import com.github.libretube.util.TranscriptMerger.CueSlice
import org.junit.Assert.assertEquals
import org.junit.Test

class TranscriptMergerTest {
    @Test
    fun testSimpleCues() {
        val lines = TranscriptMerger.merge(
            listOf(
                CueSlice(0, 2000, listOf("Hello there")),
                CueSlice(2000, 4000, listOf("General Kenobi"))
            )
        )
        assertEquals(
            listOf(TranscriptLine(0, "Hello there"), TranscriptLine(2000, "General Kenobi")),
            lines
        )
    }

    @Test
    fun testOverlappingSlicesDontDuplicateLines() {
        // parsers emit one slice per time range with every visible cue, so an overlapping
        // cue is repeated in the next slice
        val lines = TranscriptMerger.merge(
            listOf(
                CueSlice(0, 1000, listOf("first")),
                CueSlice(1000, 2000, listOf("first", "second")),
                CueSlice(2000, 3000, listOf("second"))
            )
        )
        assertEquals(
            listOf(TranscriptLine(0, "first"), TranscriptLine(1000, "second")),
            lines
        )
    }

    @Test
    fun testRollingAutoGeneratedCaptions() {
        // YouTube's auto-generated captions move the second line of a cue up into the next one
        val lines = TranscriptMerger.merge(
            listOf(
                CueSlice(0, 2000, listOf("so today we're going")),
                CueSlice(2000, 2010, listOf("so today we're going")),
                CueSlice(2010, 4000, listOf("so today we're going\nto talk about transcripts")),
                CueSlice(4000, 4010, listOf("to talk about transcripts")),
                CueSlice(4010, 6000, listOf("to talk about transcripts\nand why they matter"))
            )
        )
        assertEquals(
            listOf(
                TranscriptLine(0, "so today we're going"),
                TranscriptLine(2010, "to talk about transcripts"),
                TranscriptLine(4010, "and why they matter")
            ),
            lines
        )
    }

    @Test
    fun testLinesStartingTogetherFormOneEntry() {
        // a two-line cue must not produce two entries with the same timestamp,
        // otherwise only the second one could ever be highlighted
        val lines = TranscriptMerger.merge(
            listOf(
                CueSlice(0, 2000, listOf("Hello there,\nhow are you?")),
                CueSlice(2000, 4000, listOf("Fine,", "thanks."))
            )
        )
        assertEquals(
            listOf(
                TranscriptLine(0, "Hello there, how are you?"),
                TranscriptLine(2000, "Fine, thanks.")
            ),
            lines
        )
    }

    @Test
    fun testRepeatedLineAfterPauseIsKept() {
        val lines = TranscriptMerger.merge(
            listOf(
                CueSlice(0, 1000, listOf("[Music]")),
                CueSlice(5000, 6000, listOf("[Music]"))
            )
        )
        assertEquals(
            listOf(TranscriptLine(0, "[Music]"), TranscriptLine(5000, "[Music]")),
            lines
        )
    }

    @Test
    fun testWhitespaceIsNormalizedAndEmptyLinesDropped() {
        val lines = TranscriptMerger.merge(
            listOf(
                CueSlice(0, 1000, listOf("  lots   of\tspace  ", "", "\n")),
                CueSlice(1000, 2000, listOf("lots of space"))
            )
        )
        assertEquals(listOf(TranscriptLine(0, "lots of space")), lines)
    }

    @Test
    fun testUnsortedSlicesAreSorted() {
        val lines = TranscriptMerger.merge(
            listOf(
                CueSlice(2000, 3000, listOf("b")),
                CueSlice(0, 1000, listOf("a"))
            )
        )
        assertEquals(listOf(TranscriptLine(0, "a"), TranscriptLine(2000, "b")), lines)
    }

    @Test
    fun testIndexAt() {
        val lines = listOf(
            TranscriptLine(1000, "a"),
            TranscriptLine(3000, "b"),
            TranscriptLine(5000, "c")
        )
        assertEquals(-1, TranscriptMerger.indexAt(lines, 0))
        assertEquals(0, TranscriptMerger.indexAt(lines, 1000))
        assertEquals(0, TranscriptMerger.indexAt(lines, 2999))
        assertEquals(1, TranscriptMerger.indexAt(lines, 3000))
        assertEquals(2, TranscriptMerger.indexAt(lines, 99_000))
        assertEquals(-1, TranscriptMerger.indexAt(emptyList(), 1000))
    }
}
