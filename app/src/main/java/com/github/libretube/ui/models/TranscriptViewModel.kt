package com.github.libretube.ui.models

import android.util.Log
import androidx.lifecycle.MutableLiveData
import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.github.libretube.api.obj.Subtitle
import com.github.libretube.helpers.TranscriptHelper
import com.github.libretube.obj.TranscriptLine
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Job
import kotlinx.coroutines.launch
import java.util.Locale

class TranscriptViewModel : ViewModel() {
    sealed interface State {
        data object Loading : State
        data class Loaded(val lines: List<TranscriptLine>) : State
        data object Empty : State
        data object Error : State
    }

    val state = MutableLiveData<State>()

    /**
     * The current playback position, only updated while the transcript sheet is open.
     */
    val positionMs = MutableLiveData<Long>()

    var isSheetOpen = false

    var videoId: String? = null
        private set
    var subtitles: List<Subtitle> = emptyList()
        private set
    var selectedSubtitle: Subtitle? = null
        private set

    private var loadJob: Job? = null

    /**
     * Set the subtitles of the currently playing video. Keeps the already loaded transcript
     * if the video didn't change.
     *
     * @param preferredLanguage the user's default subtitle language, only used if no language
     * has been picked in the transcript sheet before
     */
    fun setVideo(videoId: String, subtitles: List<Subtitle>, preferredLanguage: String?) {
        if (videoId == this.videoId && state.value != null) return

        // keep the language the user picked for the previous video
        val language = selectedSubtitle?.code ?: preferredLanguage

        this.videoId = videoId
        this.subtitles = sortSubtitles(subtitles)
        selectSubtitle(pickDefaultSubtitle(language))
    }

    fun selectSubtitle(subtitle: Subtitle?) {
        selectedSubtitle = subtitle
        loadJob?.cancel()

        if (subtitle == null) {
            state.value = State.Empty
            return
        }

        state.value = State.Loading
        loadJob = viewModelScope.launch {
            state.value = try {
                val lines = TranscriptHelper.loadTranscript(subtitle)
                if (lines.isEmpty()) State.Empty else State.Loaded(lines)
            } catch (e: CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e(TAG, "Failed to load transcript", e)
                State.Error
            }
        }
    }

    fun retry() = selectSubtitle(selectedSubtitle)

    /**
     * Manually created subtitles first, auto-generated ones last.
     */
    private fun sortSubtitles(subtitles: List<Subtitle>) = subtitles
        .filter { it.url != null }
        .sortedBy { it.autoGenerated == true }

    /**
     * Prefer the user's preferred subtitle language, then the device language, then any manually
     * created subtitle, then anything at all.
     */
    private fun pickDefaultSubtitle(preferredLanguage: String?): Subtitle? {
        val deviceLanguage = Locale.getDefault().language
        fun matches(subtitle: Subtitle, language: String?) = language != null &&
            subtitle.code?.substringBefore('-')?.equals(language.substringBefore('-'), true) == true

        return subtitles.firstOrNull { matches(it, preferredLanguage) }
            ?: subtitles.firstOrNull { matches(it, deviceLanguage) }
            ?: subtitles.firstOrNull()
    }

    companion object {
        private const val TAG = "TranscriptViewModel"
    }
}
